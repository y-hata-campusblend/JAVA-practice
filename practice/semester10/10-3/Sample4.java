//randomメソッド

class Sample4
{
    public static void main(String[] args){
        int num = (int)(Math.random()*6)+1;
        //まず、ランダムに0.00・・・～0.999…を出してもらう
        /*でてきたものに×６すると、0.00...~5.999...になる。
        int型にして、小数点切り捨てる。そのあと+1したら1~6になる！

        （int）にすると型を変えられる！キャスト演算子として認識させる。（Math）なのは掛け算を先にさせたいから！（）つけないと、先にint型にでてきたすうじがかえられちゃう。0.999に*6しても無駄やんね
         */

        System.out.println("生成された数字は"+num);
    }
}