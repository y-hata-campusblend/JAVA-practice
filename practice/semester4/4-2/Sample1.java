//いろいろな演算子を利用する

class Sample1
{
    public static void main(String[] args)
    {
        int num1 = 10;
        int num2 = 5;

        System.out.println("num1とnum2にいろいろな演算を行います。");
        System.out.println("num1+num2は" + (num1+num2) + "です。");
        System.out.println("num1-num2は" + (num1-num2) + "です。");
        System.out.println("num1*num2は" + (num1*num2) + "です。");
        System.out.println("num1/num2は" + (num1/num2) + "です。");
        System.out.println("num1%num2は" + (num1%num2) + "です。");
        System.out.println("3+num1は"+ (3+num1) + "です");
    }
}