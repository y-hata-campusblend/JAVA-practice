//文字と数値を入力する
class Sample6
{
 public static void main(String[] args)
 {
     System.out.println("10新数の10は10です");
     System.out.println("10新数の10は"+ 10 +"です。");
     System.out.println("16新数の10は"+ 0x10 +"です。");
     System.out.println("16進数のFは" + 0xF +"です。");
     System.out.println(123);
     System.out.println("\\"+100+"円もらった");
     System.out.println("またあした");
     System.out.println("1\t2\t3");
     System.out.println(6 + "\t" + 024 + "\t" + 015);
     System.out.println(6 + "\t" + 0x14 + "\t" + 0xD);
 }
}